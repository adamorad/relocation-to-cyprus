#!/usr/bin/env node
// Writes docs/topics-mapping.md from lib/topic-map.ts (the single source).
// Run after changing the mapping:  node scripts/gen-topics-mapping.mjs
// Check only (no write; fails if anything is unmapped or the doc is stale):
//   node scripts/gen-topics-mapping.mjs --check   (pnpm qa:topics)
// Uses Node's built-in TypeScript type stripping plus a small resolver for the
// project's extensionless and "@/" imports (Node 22.15+ / 24).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

registerHooks({
	resolve(spec, ctx, next) {
		let s = spec;
		if (s.startsWith("@/")) s = pathToFileURL(join(ROOT, s.slice(2))).href;
		if (
			(s.startsWith(".") || s.startsWith("file:")) &&
			!/\.[mc]?[jt]sx?$/.test(s)
		) {
			const base = s.startsWith("file:")
				? fileURLToPath(s)
				: fileURLToPath(new URL(s, ctx.parentURL));
			for (const ext of [".ts", ".tsx"]) {
				if (existsSync(base + ext))
					return next(pathToFileURL(base + ext).href, ctx);
			}
		}
		return next(s, ctx);
	},
});

const map = await import(pathToFileURL(join(ROOT, "lib/topic-map.ts")).href);
const { TOPICS, PROPERTY_AREA } = await import(
	pathToFileURL(join(ROOT, "lib/topics.ts")).href
);
const { topicMapProblems } = await import(
	pathToFileURL(join(ROOT, "lib/topic-map-check.ts")).href
);

const problems = topicMapProblems();
if (problems.length > 0) {
	console.error(`Mapping problems:\n  ${problems.join("\n  ")}`);
	process.exit(1);
}

// The eight topics, then the Property area (a primary home, never a secondary).
const HOMES = [...TOPICS, PROPERTY_AREA];
const name = Object.fromEntries(HOMES.map((t) => [t.slug, t.name]));
const hubOf = (slug) =>
	slug === "moving-here" ? "/moving-to-cyprus/" : `/${slug}/`;
const items = map.allTopicItems();
const KIND = { guide: "Guides", directory: "Directories", tool: "Tools" };
// Titles are shown as-is except em dashes (house rule), which become colons.
const esc = (s) =>
	String(s)
		.replace(/\s*\u2014\s*/g, ": ")
		.replace(/\|/g, "\\|");

const lines = [];
lines.push("# Topic mapping");
lines.push("");
lines.push(
	'Every guide, directory and live tool has one primary topic (its breadcrumb, hub and "More on" block), up to two secondary topics (it is also listed on those hubs, after the primary items) and the cities it is specific to (empty means island-wide).',
);
lines.push("");
lines.push(
	"Property items (Phase 4) have the Property area as their primary home instead of a topic: they are listed on `/property/` (from `PROPERTY_ITEMS` in `lib/property.ts`, which must match the rows mapped to Property below), their breadcrumb is Home > Property > item, and they appear on an everyday topic hub only where a secondary topic is given. The /guides/, /tools/ and /sections/ indexes still list them under a Property filter.",
);
lines.push("");
lines.push(
	"Source of truth: `lib/topic-map.ts`. This file is generated by `node scripts/gen-topics-mapping.mjs`; do not edit it by hand. `pnpm build` fails if any item is unmapped (`lib/topic-map-check.ts`, called from `app/sitemap.ts`).",
);
lines.push("");
lines.push(
	"Decisions were made on the owner's behalf in Phase 2A and are open for review. Rows with a reason are the non-obvious ones.",
);
lines.push("");
lines.push("## Counts");
lines.push("");
lines.push(
	"| Topic | Hub | Guides | Directories | Tools | Total primary | Listed on hub (incl. secondary) |",
);
lines.push("| --- | --- | ---: | ---: | ---: | ---: | ---: |");
for (const t of HOMES) {
	const p = items.filter((i) => i.topic === t.slug);
	const c = (type) => p.filter((i) => i.type === type).length;
	// Property's hub lists exactly its primary items (lib/property.ts).
	const hubTotal =
		t.slug === PROPERTY_AREA.slug
			? p.filter((i) => i.listed).length
			: (() => {
					const hub = map.itemsForTopic(t.slug);
					return hub.guides.length + hub.directories.length + hub.tools.length;
				})();
	lines.push(
		`| ${t.name} | \`${hubOf(t.slug)}\` | ${c("guide")} | ${c("directory")} | ${c("tool")} | ${p.length} | ${hubTotal} |`,
	);
}
lines.push(
	`| **All** | | ${items.filter((i) => i.type === "guide").length} | ${items.filter((i) => i.type === "directory").length} | ${items.filter((i) => i.type === "tool").length} | ${items.length} | |`,
);
lines.push("");
lines.push(
	'Directories marked *(not listed)* were de-listed in Phase 3C (commit b0899d2). They keep a topic for their own breadcrumb and "More on" block but are not shown on hubs, indexes, other pages or the sitemap.',
);

for (const type of ["guide", "directory", "tool"]) {
	lines.push("");
	lines.push(`## ${KIND[type]}`);
	lines.push("");
	lines.push("| Item | Primary topic | Secondary | Cities | Reason |");
	lines.push("| --- | --- | --- | --- | --- |");
	const rows = items
		.filter((i) => i.type === type)
		.sort(
			(a, b) =>
				HOMES.findIndex((t) => t.slug === a.topic) -
					HOMES.findIndex((t) => t.slug === b.topic) ||
				a.slug.localeCompare(b.slug),
		);
	for (const i of rows) {
		const a = map.getAssignment(type, i.slug);
		const label = `[${esc(i.title)}](${i.href})${i.listed ? "" : " *(not listed)*"}`;
		lines.push(
			`| ${label} | ${name[i.topic]} | ${i.also.map((s) => name[s]).join(", ")} | ${i.cities.join(", ")} | ${esc(a?.why ?? "")} |`,
		);
	}
}
lines.push("");

const out = join(ROOT, "docs", "topics-mapping.md");
if (process.argv.includes("--check")) {
	const current = existsSync(out) ? readFileSync(out, "utf8") : "";
	if (current !== lines.join("\n")) {
		console.error(
			"docs/topics-mapping.md is out of date: run node scripts/gen-topics-mapping.mjs",
		);
		process.exit(1);
	}
	console.log(
		`Topic mapping OK: ${items.length} items mapped, doc up to date.`,
	);
	process.exit(0);
}
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out} (${items.length} items)`);
